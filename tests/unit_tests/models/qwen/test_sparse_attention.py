def test_build_sparse_prepend_memory_pattern_32_4_8():
    """Verify _build_sparse_prepend_memory_pattern(seq_len=32, group_size=4, segment_size=8)."""
    mask = _build_sparse_prepend_memory_pattern(32, 4, 8, torch.device("cpu"))
    expected = torch.tensor(_EXPECTED_MASK_32_4_8, dtype=torch.bool)

    assert mask.shape == expected.shape, f"Shape mismatch: {mask.shape} vs {expected.shape}"
    assert mask.dtype == torch.bool
    assert torch.equal(mask, expected), (
        f"Mask mismatch — {mask.sum().item()} attend positions vs expected {expected.sum().item()}"
    )


def test_build_sparse_prepend_memory_pattern_32_4_8_swa_only():
    """Verify _build_sparse_prepend_memory_pattern(seq_len=32, group_size=4, segment_size=8, swa_only=True).

    SWA = Sliding Window Attention. When swa_only=True, rule ② (t -> m) is
    skipped, so the t->m block (rows 8..39, cols 0..7) is all zeros.
    Rules ① (t->t), ③ (m->t), and ④ (m->m) remain the same as the
    swa_only=False case.
    """
    mask = _build_sparse_prepend_memory_pattern(32, 4, 8, torch.device("cpu"), swa_only=True)
    expected = torch.tensor(_EXPECTED_MASK_32_4_8_SWA_ONLY, dtype=torch.bool)

    assert mask.shape == expected.shape, f"Shape mismatch: {mask.shape} vs {expected.shape}"
    assert mask.dtype == torch.bool
    assert torch.equal(mask, expected), (
        f"Mask mismatch — {mask.sum().item()} attend positions vs expected {expected.sum().item()}"
    )
